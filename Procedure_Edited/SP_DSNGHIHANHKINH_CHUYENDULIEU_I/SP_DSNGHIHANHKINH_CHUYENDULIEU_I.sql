ALTER PROCEDURE [dbo].[SP_DSNGHIHANHKINH_CHUYENDULIEU_I]
(@NGAYCUOITHANG NVARCHAR(50),@T_MA NVARCHAR(7))
AS
BEGIN
	DECLARE @NGAY DATE 
	SET @NGAY = CONVERT(DATETIME,@NGAYCUOITHANG)


	INSERT INTO IT_SOGIONGHIHANHKINH (NV_MA ,NAM ,THANG ,TONGSOGIO,NV_GIOITINH ,NV_NGAYVAO ,TINHNGHIVIEC  )
	SELECT ST_NHANVIEN.NV_Ma,
			RIGHT(@T_MA,4) AS NAM ,
			LEFT(@T_MA,2) AS THANG ,
			TONGSOGIODUOCHUONG = 1.5 - SUM(CASE WHEN NOT IT_PHUNUHANHKINH.NV_MA IS NULL THEN 0.5 ELSE 0 END),
			NV_GioiTinh= isnull(ST_NHANVIEN.NV_GioiTinh ,0),
			NV_Ngayvao ,0
	FROM ST_NHANVIEN LEFT JOIN IT_PHUNUHANHKINH ON ST_NHANVIEN.NV_Ma = IT_PHUNUHANHKINH.NV_MA
													AND MONTH(IT_PHUNUHANHKINH.NGAY)= MONTH(@NGAY) 
													AND YEAR(IT_PHUNUHANHKINH.NGAY)= YEAR(@NGAY)
					INNER JOIN ST_DONVI ON ST_NHANVIEN.DV_MA = ST_DONVI.DV_MA AND ISNULL(DV_LocBB ,0) = 0 AND ISNULL(DV_TV ,0) <> 1
	WHERE NV_GioiTinh = 0
			AND ST_NHANVIEN.NV_Ma NOT IN (SELECT NV_Ma FROM ST_NHANVIENTHOIVIEC )
			AND ST_DONVI.DV_MA NOT LIKE '%CG%' AND ST_DONVI.DV_MA NOT IN ('BGD','BGDX')
			--- NGOAI LE
			AND YEAR(GETDATE()) - YEAR(NV_NGAYSINH) < 55 
			AND ST_NHANVIEN.CVU_MA NOT IN ('PCN','CNHIEM','TL','XT','PGD','GD','PHL','HL','T')
			AND NV_Ngayvao <= @NGAY
			AND ST_NHANVIEN.NV_MA NOT IN (SELECT NV_MA 
											FROM IT_SOGIONGHIHANHKINH 
											WHERE THANG =  MONTH(@NGAY) AND NAM = YEAR(@NGAY) AND ISNULL(TINHNGHIVIEC,0) = 1)
	GROUP BY  ST_NHANVIEN.NV_Ma,ST_NHANVIEN.NV_Ten,ST_NHANVIEN.DV_MA,ST_NHANVIEN.NV_Ngayvao,NV_GioiTinh
	
	/* Đợi khi nào NS có yêu cầu sửa phần mềm thì tính
	--Andrew Cập nhật lại trường hợp những người đi làm không thỏa đk ít nhất đủ 3 ngày liên tục
	---------------
	UPDATE IT_SOGIONGHIHANHKINH
	SET TONGSOGIO = 0
	WHERE NAM = RIGHT(@T_MA,4)
		AND	THANG = LEFT(@T_MA,2)
		AND TONGSOGIO > 0
		AND NV_MA NOT IN(SELECT DISTINCT NV_MA--,COUNT(T1.DAY_CHA)--,T1.DAY_CHA,COUNT(T1.DAY_CHA) AS SoLanLienTiep 
							FROM (
												SELECT ROW_NUMBER() OVER (PARTITION BY NV_MA ORDER BY [QT_NGAY]) DATE_RANK
														,(DATEPART(DAY, QT_NGAY) - ROW_NUMBER() OVER (PARTITION BY NV_MA ORDER BY [QT_NGAY])) AS DAY_CHA
														, NV_MA, QT_NGAY, CC_GIOBINHTHUONG
												FROM ST_GIOQUETTHE
												WHERE YEAR(QT_NGAY) = RIGHT(@T_MA,4)
														AND MONTH(QT_NGAY) = LEFT(@T_MA,2)
														AND CC_GIOBINHTHUONG <> 0
														AND CC_GIOBINHTHUONG IS NOT NULL
														--AND NV_MA = '326088'
														-- ORDER BY NV_MA, QT_NGAY
												) AS T1
							--WHERE T1.NV_MA = '312155'
							GROUP BY NV_MA,T1.DAY_CHA
							HAVING COUNT(DAY_CHA) >= 3						
						)
	*/
END

