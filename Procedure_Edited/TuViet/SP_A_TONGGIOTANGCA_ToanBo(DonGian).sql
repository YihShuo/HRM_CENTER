ALTER  PROCEDURE [dbo].[SP_A_TONGGIOTANGCA_ToanBo]
	@MANV nvarchar(100),@NGAY DATETIME--,@TOTAL FLOAT OUTPUT
AS
Begin
Declare 
	@D INT,
	@M INT,
	@Y INT,
	@I INT,
	@J INT,
	@SQL nvarchar(4000)
--	set @NGAY = '2011-12-01'
	SET @D=DAY(@NGAY)
	SET @M=MONTH(@NGAY)
	SET @Y=YEAR(@NGAY)
	SET @I=1
	SET @J=1
	--------------
	SET @SQL='SELECT NV_Ma,TONGGIOTC=sum('
	WHILE @I<=31
	BEGIN
		SET @SQL = @SQL + 'isnull(giotangca_'+ RTRIM(CONVERT(CHAR(2),@I)) +',0)+'
		SET @I=@I+1
	END
	SET @SQL=LEFT(@SQL,LEN(@SQL)-1)+') '
	SET @SQL=@SQL+'FROM ST_VAORA_MACHINE INNER JOIN ST_NHANVIEN '
	SET @SQL=@SQL+'ON ST_VAORA_MACHINE.MANV=ST_NHANVIEN.NV_MA '
	SET @SQL=@SQL+'WHERE DV_MA<>''VPCT'' '
	SET @SQL=@SQL+'AND NAM='+CONVERT(CHAR(4),@Y)+' '
	SET @SQL=@SQL+'AND THANG<'+CONVERT(CHAR(2),@M)+' '
	SET @SQL=@SQL+'AND MANV='+''''+ @MANV + ''' '
	SET @SQL=@SQL+'GROUP BY NV_Ma'
	
	print (@SQL)
	Exec (@SQL)
	--return @TOTAL
End

