ALTER FUNCTION [dbo].[fnThongKeGioCongTheoXuongDiemDanhNgoaiGio] (@XUONG NVARCHAR(50),@NGAYDD datetime,@NGAYBD DATETIME,@NGAYKT DATETIME)
RETURNS TABLE 
AS
RETURN 
(

	SELECT IT_DIEMDANHHANGNGAY.NV_MA,X_MA_,IT_DIEMDANHHANGNGAY.DV_MA,DV_TEN 
			,0 AS TONGBT
			,SUM( ISNULL(CC_GIOTANGCA,0) ) AS TONGTC 
			,TTCV  --Andrew
	FROM ST_GIOQUETTHE_ INNER JOIN IT_DIEMDANHHANGNGAY ON IT_DIEMDANHHANGNGAY.NV_MA = ST_GIOQUETTHE_.NV_MA 
						INNER JOIN ST_DONVI ON ST_DONVI.DV_MA = IT_DIEMDANHHANGNGAY.DV_MA
						----Andrew-----
					   LEFT JOIN ST_NHANVIEN ON ST_GIOQUETTHE_.NV_MA=ST_NHANVIEN.NV_Ma
					   LEFT JOIN ST_CONGVIEC ON  ST_NHANVIEN.CV_MA=ST_CONGVIEC.CV_MA
	WHERE QT_NGAY >= @NGAYBD AND QT_NGAY <= @NGAYKT
							AND NGAY  = @NGAYDD
							AND X_MA_ = @XUONG
							AND X_MA_ NOT IN ('KB','TAM','DT')
	GROUP BY X_MA_,IT_DIEMDANHHANGNGAY.DV_MA,DV_TEN,IT_DIEMDANHHANGNGAY.NV_MA,TTCV

)

