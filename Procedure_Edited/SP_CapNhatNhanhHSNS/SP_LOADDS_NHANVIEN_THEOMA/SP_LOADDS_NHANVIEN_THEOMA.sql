ALTER PROCEDURE [dbo].[SP_LOADDS_NHANVIEN_THEOMA]
@MaNV NVARCHAR(50)
AS
begin	
	SELECT MTCV = 'Xem',
			PTCV = 'Xem',
			NHOMMTCV = 'XemNhom',
			NHOMPTCV = 'XemNhom',
			ST_NHANVIEN.NV_Ma AS NV_MA,
			ST_NHANVIEN.NV_Ten AS NV_TEN,
			ST_NHANVIEN.NV_MaQL AS NV_MAQL,
			ST_NHANVIEN.DV_MA AS DV_MA,
			ST_NHANVIEN.DV_MA_ AS DV_MA_, 
			ST_NHANVIEN.NV_MaTu AS NV_MATU, 
			ST_NHANVIEN.NV_GioiTinh AS NV_GIOITINH,
			(CASE WHEN ISNULL(NV_NAMSINH,0) = 0  THEN (CONVERT(NVARCHAR(10),
			ST_NHANVIEN.NV_Ngaysinh,105)) ELSE (LEFT(CONVERT(NVARCHAR(10),ST_NHANVIEN.NV_Ngaysinh,21),4)) END) AS NV_NGAYSINH,
			NV_TUOI,
			ST_NHANVIEN.NV_NoiSinh AS NV_NOISINH, 
			ST_NHANVIEN.NV_DiaChi AS NV_DIACHI, 
			ST_NHANVIEN.Mail AS Mail,
			ST_NHANVIEN.TT_MA AS TT_MA, 
			ST_NHANVIEN.QT_MA AS QT_MA,
			ST_NHANVIEN.DT_MA AS DT_MA, 
			ST_NHANVIEN.TG_MA AS TG_MA, 
			ST_NHANVIEN.NV_Thuongtru AS NV_THUONGTRU,
			ST_NHANVIEN.NV_Honnhan AS NV_HONNHAN, 
			ST_NHANVIEN.NV_Socon AS NV_SOCON ,
			ST_NHANVIEN.NOIDUNGBS AS NOIDUNGBS, 
			ST_NHANVIEN.NV_CMND AS NV_CMND,
			ST_NHANVIEN.NV_NgayCapCMND AS NV_NGAYCAPCMND, 
			ST_NHANVIEN.NV_NoiCapCMND AS NV_NOICAPCMND,
			ST_NHANVIEN.NV_DTNhaRieng AS NV_DTNHARIENG, 
			ST_NHANVIEN.NV_DTDiDong AS NV_DTDIDONG,
			ST_NHANVIEN.NV_Ngayvao AS NV_NGAYVAO,
			ST_NHANVIEN.NV_Ngayvao AS TUNGAY,
			ST_NHANVIEN.NV_Ngayvao AS DENNGAY,
			ST_NHANVIEN.NV_Hinh AS NV_HINH, 
			ST_NHANVIEN.HV_MA AS HV_MA,
			ST_NHANVIEN.TH_MA AS TH_MA, 
			ST_NHANVIEN.NN_MA AS NN_MA, 
			ST_CONGVIEC.CV_TEN AS CV_TEN,
			ST_NHANVIEN.CVU_MA AS CVU_MA, 
			ST_NHANVIEN.NV_Ngaybonhiem AS NV_NGAYBONHIEM, 
			ST_NHANVIEN.CM_MA AS CM_MA, 
			ST_NHANVIEN.NV_Congdoan AS NV_CONGDOAN, 
			ST_NHANVIEN.NV_NgayvaoCD AS NV_NGAYVAOCD,
			ST_NHANVIEN.NV_THOIVIEC AS NV_THOIVIEC, 
			ST_NHANVIEN.NV_NgayTV AS NV_NGAYTV,
			ST_NHANVIEN.NV_NGAYKHD AS NV_NGAYKHD, 
			ST_NHANVIEN.QH_MA AS QH_MA, 
			ST_NHANVIENTHOIVIEC.LTV_MA AS LTV_MA,
			ST_HOPDONGLAODONG.HD_LUONGCB AS HD_LUONGCB,
			ST_NHANVIEN.NV_DAKYHDLD AS NV_DAKYHDLD,
			ST_NHANVIEN.BSHS AS BSHS,
			ST_NHANVIEN.DANGVIEN AS DANGVIEN,
			ST_NHANVIEN.NGAYVAODANG AS NGAYVAODANG,
			ST_NHANVIEN.NOIVAO AS NOICONGTAC,
			ST_NHANVIEN.HLHTNVN AS TNVN,
			ST_NHANVIEN.TRINHDOCHINHTRI AS TRINHDO,
			ST_NHANVIEN.CV_MA AS CV_MA, 
			ST_HOPDONGLAODONG.L_MA, 
			L_TEN,ST_NHANVIENTHOIVIEC.LTV_MA,
			TV_LYDO,
			CHK_DOANVIEN= (CASE WHEN IT_CONGDOAN.SOTHE IS NOT NULL THEN 1 ELSE 0 END),
			ST_NHANVIEN.MASOTHUE ,
			ST_NHANVIEN.SOTAIKHOAN,
			NV_NAMSINH,NV_Ngaysinh AS NV_NGAYSINHTT,
			-------------------------Địa Chỉ---------------------------
			--------Quê Quán
            NV_TinhQQ ,
            NV_QuanHuyenQQ AS QuanHuyen_QQ ,
            NV_XaPhuongQQ  AS XaPhuong_QQ,
			--Andrew
			dbo.fn_LayTenQuanHuyen(NV_TinhQQ,NV_QuanHuyenQQ) AS TenQH_QQ,
			dbo.fn_LayTenXaPhuong(NV_TinhQQ,NV_QuanHuyenQQ,NV_XaPhuongQQ) AS TenXP_QQ,
			--------Thường Trú
            NV_TinhDC ,
			NV_QuanHuyenDC AS QuanHuyen_DC,
			NV_XaPhuongDC AS XaPhuong_DC,
			--Andrew
			dbo.fn_LayTenQuanHuyen(NV_TinhDC,NV_QuanHuyenDC) AS TenQH_DC,
			dbo.fn_LayTenXaPhuong(NV_TinhDC,NV_QuanHuyenDC,NV_XaPhuongDC) AS TenXP_DC,
            NV_SoNhaDC,
			-----------------------------------------------------------
			ST_NHANVIEN.IT_DDNGHIVIEC AS CHUYENTAM,  
			TenVaccine_1,
			NgayVaccine_1,
			TenVaccine_2,
			NgayVaccine_2,
			TenVaccine_3,
			NgayVaccine_3,
			TenVaccine_4,
			NgayVaccine_4,
			TenVaccine_5,
			NgayVaccine_5,
			TenVaccine_6,
			NgayVaccine_6
			-- ,
			--ST_NHANVIEN.KHUA AS KHUA ,
			--ST_NHANVIEN.KHUB AS KHUB
	FROM ST_NHANVIEN LEFT JOIN ST_NHANVIENTHOIVIEC ON ST_NHANVIEN.NV_MA = ST_NHANVIENTHOIVIEC.NV_MA 
					LEFT JOIN ST_HOPDONGLAODONG ON ST_NHANVIEN.NV_MA = ST_HOPDONGLAODONG.NV_MA 
					LEFT JOIN ST_CONGVIEC ON ST_CONGVIEC.CV_MA = ST_NHANVIEN.CV_MA 
					LEFT JOIN ST_HOPDONG_LOAI ON ST_HOPDONGLAODONG.L_MA = ST_HOPDONG_LOAI.L_MA 
					LEFT JOIN IT_CONGDOAN ON ST_NHANVIEN.NV_MA = IT_CONGDOAN.SOTHE  
					left join st_donvi on st_nhanvien.DV_MA = st_donvi.DV_MA 					
	WHERE LEN(ST_NHANVIEN.NV_MA) = 6 AND ST_NHANVIEN.NV_Ma = @MaNV
	ORDER BY ST_NHANVIEN.NV_MA ASC 
END

