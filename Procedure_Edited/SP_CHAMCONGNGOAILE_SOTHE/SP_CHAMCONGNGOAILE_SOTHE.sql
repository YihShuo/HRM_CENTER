ALTER PROCEDURE [dbo].[SP_CHAMCONGNGOAILE_SOTHE]
	@NGAY datetime,@SOTHE NVARCHAR(50)	
AS
Begin
	IF EXISTS (Select ST_NHANVIEN.NV_Ma 
		From ST_NhanVien
		where ST_NHANVIEN.NV_MA in(Select ST_GIOQUETTHE.NV_MA from ST_GIOQUETTHE 
		INNER JOIN ST_VAORA ON ST_GIOQUETTHE.NV_MA=ST_VAORA.NV_MA
		AND ST_GIOQUETTHE.QT_NGAY=ST_VAORA.QT_NGAY
		AND ST_GIOQUETTHE.CA_MA=ST_VAORA.CA_MA
		where ST_GIOQUETTHE.QT_NGAY=@NGAY AND NOT QT_GIOVAO IS NULL)
		AND ST_NHANVIEN.NV_MA not in(Select NV_MA from ST_NhanvienThoiViec where TV_Ngaythoiviec<@NGAY)
		AND DV_MA NOT LIKE 'NV%' AND DV_MA NOT LIKE '%CG%' AND DV_MA <> 'BGD' AND ST_NHANVIEN.NV_MA=@SOTHE)
	BEGIN
		declare @GIOTANGCA float
		
		exec SP_CHAMCONGN  @NGAY,@SOTHE,0,1,0,0,0,1,0,0,0,0,0,1,1,0,0,1
		
		Select @GIOTANGCA=CC_GIOTANGCA FROM ST_GIOQUETTHE 
		WHERE NV_MA=@SOTHE AND QT_NGAY=@NGAY 
		
		--IF @GIOTANGCA=0.5
		--	Update ST_GIOQUETTHE Set CC_GIOTANGCA=0, CC_GIOTANGCAS = 0,QT_NGUOICAPNHAT='admin',QT_NGAYCAPNHAT=GETDATE() 
		--	From ST_GIOQUETTHE
		--	Where NV_Ma=@SOTHE and QT_Ngay=@NGAY and CA_MA <> 'Ca03'
	END	
end

GO