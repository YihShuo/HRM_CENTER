ALTER PROCEDURE [dbo].[SP_CAPNHATHDLD_U]
(@T_MA NVARCHAR(50) , @NGUOITAO NVARCHAR(50), @NGAYTAO DATETIME)
AS
BEGIN
UPDATE ST_HOPDONGLAODONG 
SET 
HD_Luongtoithieu = (SELECT LUONGTOITHIEU FROM IT_LUONGTOITHIEU),
HD_LuongCB = ISNULL(LUONGCBMOI,0) ,
HD_TrocapCMNV = ISNULL(TCCMMOI,0) ,
HD_TrocapCV = ISNULL(TCCVMOI,0) ,
HD_TrocapNN = ISNULL(TCNNMOI,0) ,
HD_TrocapUD = ISNULL(TCUDMAYMOI,0) ,
HD_TroCapQAQIP = ISNULL(TCQAQIPMOI,0) ,
HD_TrocapThoRap = ISNULL(TCTHORAPMOI,0) ,
HD_TrocapHSE = ISNULL(TCHSEMOI,0) ,
TCCBVP = ISNULL(TCCBVPMOI,0) ,
TCCBTS = ISNULL(TCCBTSMOI,0) ,
HD_PhuCapkhac = ISNULL(TCKHACMOI,0) ,
HD_TrocapHMPT = ISNULL(TCHMPTMOI,0) ,
HD_TCHOTRODONGPHUC = ISNULL(TCHOTRODONGPHUCMOI,0) ,
HD_TCCHAMLOGIADINH = ISNULL(TCCHAMLOGIADINHMOI,0) ,
TCBBTHANG = ISNULL(TCBBTHANGMOI,0) ,
TCBBHT = ISNULL(TCBBNMOI,0),
TENNGACH = IT_NGACH.N_TEN,
NGACH = LEFT(IT_NGACH.N_MA,1),
BAC = IT_BAC.B_TEN,
 ST_HOPDONGLAODONG.BL_MA = IT_BANGLUONGTHANG0109.BACLUONGMOI,
ST_HOPDONGLAODONG.HD_HeSo = IT_BANGLUONGTHANG0109.HESOMOI,
ST_HOPDONGLAODONG.HD_NGUOITAO = @NGUOITAO ,
ST_HOPDONGLAODONG.HD_NGAYTAO = @NGAYTAO,
ST_HOPDONGLAODONG.HD_CongviecDH = IT_BANGLUONGTHANG0109.DHNN,
ST_HOPDONGLAODONG.HD_KHONGHUONGCHUYENCAN=IT_BANGLUONGTHANG0109.KHCC,
ST_HOPDONGLAODONG.HD_HTNG = IT_BANGLUONGTHANG0109.TCHTNGMOI,
ST_HOPDONGLAODONG.HD_DQTV = IT_BANGLUONGTHANG0109.TCDQTVMOI,
ST_HOPDONGLAODONG.HD_PCCC = IT_BANGLUONGTHANG0109.TCPCCCMOI
 
from IT_BANGLUONGTHANG0109 INNER JOIN ST_HOPDONGLAODONG ON IT_BANGLUONGTHANG0109.NV_Ma = ST_HOPDONGLAODONG.NV_MA
INNER JOIN ST_NHANVIEN ON ST_HOPDONGLAODONG.NV_MA = ST_NHANVIEN.NV_MA
INNER JOIN ST_DONVI ON ST_NHANVIEN.DV_MA = ST_DONVI.DV_MA
LEFT JOIN ST_CONGVIEC ON ST_NHANVIEN.CV_MA = ST_CONGVIEC.CV_MA
LEFT JOIN ST_CHUCVU  ON ST_NHANVIEN.CVU_MA = ST_CHUCVU.CVU_MA
INNER JOIN IT_BAC ON IT_BANGLUONGTHANG0109.BACLUONGMOI = IT_BAC.B_MA
INNER JOIN IT_BANGLUONG ON IT_BAC.BL_MA =IT_BANGLUONG.BL_MA 
INNER JOIN IT_NGACH ON IT_BAC.N_MA =IT_NGACH.N_MA 
WHERE T_MA = @T_MA AND IT_BANGLUONGTHANG0109.LOAI_TL = 'TT'
AND ST_NHANVIEN.NV_Ma not in ('000998')
AND ST_NHANVIEN.DV_MA NOT LIKE N'%CG%'
AND ST_NHANVIEN.DV_MA NOT LIKE N'%BGD%'
AND	ST_NHANVIEN.DV_MA NOT LIKE('HCM%')
--AND IT_BANGLUONGTHANG0109.NV_Ma = '60903'
--ORDER BY IT_BANGLUONGTHANG0109.NV_Ma
END

