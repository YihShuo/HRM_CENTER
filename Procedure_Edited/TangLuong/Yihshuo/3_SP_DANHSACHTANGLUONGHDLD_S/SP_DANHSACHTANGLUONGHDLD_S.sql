ALTER PROCEDURE [dbo].[SP_DANHSACHTANGLUONGHDLD_S]
(@T_MA NVARCHAR(50))
AS
BEGIN

SELECT IT_BANGLUONGTHANG0109.NV_Ma,
ST_NHANVIEN.NV_Ten,
ST_NHANVIEN.DV_MA AS DV_MA,
ST_CONGVIEC.CV_TEN ,
ST_CHUCVU .CVU_Ten,
DHNN,
KHCC,
HD_LuongCB = ISNULL(ST_HOPDONGLAODONG.HD_LuongCB,0) ,
HD_TrocapCMNV = ISNULL(ST_HOPDONGLAODONG.HD_TrocapCMNV ,0) ,
HD_TrocapCV = ISNULL(ST_HOPDONGLAODONG.HD_TrocapCV ,0) ,
HD_TrocapNN = ISNULL(ST_HOPDONGLAODONG.HD_TrocapNN ,0) ,
HD_TrocapUD = ISNULL(ST_HOPDONGLAODONG.HD_TrocapUD ,0) ,
HD_TroCapQAQIP = ISNULL(ST_HOPDONGLAODONG.HD_TroCapQAQIP ,0) ,
HD_TrocapThoRap = ISNULL(ST_HOPDONGLAODONG.HD_TrocapThoRap ,0) ,
HD_TrocapHSE = ISNULL(ST_HOPDONGLAODONG.HD_TrocapHSE ,0) ,
TCCBVP = ISNULL(ST_HOPDONGLAODONG.TCCBVP ,0) ,
TCCBTS = ISNULL(ST_HOPDONGLAODONG.TCCBTS ,0) ,
HD_PhuCapkhac = ISNULL(ST_HOPDONGLAODONG.HD_PhuCapkhac ,0) ,
HD_TrocapHMPT = ISNULL(ST_HOPDONGLAODONG.HD_TrocapHMPT ,0) ,
HD_TCHOTRODONGPHUC = ISNULL(ST_HOPDONGLAODONG.HD_TCHOTRODONGPHUC ,0) ,
HD_TCCHAMLOGIADINH = ISNULL(ST_HOPDONGLAODONG.HD_TCCHAMLOGIADINH ,0) ,
TCBBTHANG = ISNULL(ST_HOPDONGLAODONG.TCBBTHANG ,0) ,
TCBBHT = ISNULL(ST_HOPDONGLAODONG.TCBBHT ,0),
LUONGCBMOI,
TCCMMOI,
TCCVMOI,
TCNNMOI,
TCUDMAYMOI,
TCQAQIPMOI,
TCTHORAPMOI,
TCHSEMOI,
TCCBVPMOI,
TCCBTSMOI,
TCKHACMOI,
TCHMPTMOI,
TCHOTRODONGPHUCMOI,
TCCHAMLOGIADINHMOI,
TCBBTHANGMOI,
TCBBNMOI,
TCMOITRUONGMOI,
TCHTNGMOI,
TCDQTVMOI,
TCPCCCMOI
from IT_BANGLUONGTHANG0109 INNER JOIN ST_HOPDONGLAODONG ON IT_BANGLUONGTHANG0109.NV_Ma = ST_HOPDONGLAODONG.NV_MA
INNER JOIN ST_NHANVIEN ON ST_HOPDONGLAODONG.NV_MA = ST_NHANVIEN.NV_MA
INNER JOIN ST_DONVI ON ST_NHANVIEN.DV_MA = ST_DONVI.DV_MA
LEFT JOIN ST_CONGVIEC ON ST_NHANVIEN.CV_MA = ST_CONGVIEC.CV_MA
LEFT JOIN ST_CHUCVU  ON ST_NHANVIEN.CVU_MA = ST_CHUCVU.CVU_MA
WHERE T_MA = @T_MA  AND LOAI_TL = 'TT'
AND ST_NHANVIEN.NV_Ma not in ('000998')
AND ST_NHANVIEN.DV_MA NOT LIKE N'%CG%'
AND ST_NHANVIEN.DV_MA NOT LIKE N'%BGD%'
ORDER BY IT_BANGLUONGTHANG0109.NV_Ma
END

