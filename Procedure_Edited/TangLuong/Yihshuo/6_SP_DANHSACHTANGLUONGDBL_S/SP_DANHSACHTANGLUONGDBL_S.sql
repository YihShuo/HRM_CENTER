ALTER PROCEDURE [dbo].[SP_DANHSACHTANGLUONGDBL_S]
(@T_MA NVARCHAR(50))
AS
BEGIN
	SELECT IT_BANGLUONGTHANG0109.NV_Ma,
	--DBL_Ngaybatdau = DATEADD(MM,1,DATEADD(YY,1, CONVERT(DATE,@T_MA + '-'+'01',102))),
	DBL_Ngaybatdau =CONVERT(DATE,@T_MA + '-'+'01',102),
	DBL_Soquyetdinh = '01' ,
	DBL_Heso = IT_BANGLUONGTHANG0109.HESOMOI ,
	DBL_LuongCB = IT_BANGLUONGTHANG0109.LUONGCBMOI ,
	DBL_PhuCap = IT_BANGLUONGTHANG0109.TCCVMOI + IT_BANGLUONGTHANG0109.TCCMMOI + IT_BANGLUONGTHANG0109.TCCBTSMOI ,
	CV_MA = ST_NHANVIEN.CV_MA ,
	CVU_MA = ST_NHANVIEN.CVU_MA ,
	DHNN,
	KHCC,
	LDCM = 0,
	DBL_PhuCapKhac = IT_BANGLUONGTHANG0109.TCKHACMOI,
	DBL_TrocapCV  = IT_BANGLUONGTHANG0109.TCCVMOI ,
	DBL_TrocapUDMAY = IT_BANGLUONGTHANG0109.TCUDMAYMOI,
	DBL_TrocapCMNV = IT_BANGLUONGTHANG0109.TCCMMOI,
	DBL_TrocapNN = IT_BANGLUONGTHANG0109.TCNNMOI,
	DBL_TrocapHMPT = IT_BANGLUONGTHANG0109.TCHMPTMOI,
	DBL_TroCapQLSX = IT_BANGLUONGTHANG0109.TCCBTSMOI,
	DBL_TroCapCBVP = IT_BANGLUONGTHANG0109.TCCBVPMOI,
	DBL_TroCapBBHT = IT_BANGLUONGTHANG0109.TCBBNMOI,
	DBL_TroCapBBTHANG = IT_BANGLUONGTHANG0109.TCBBTHANGMOI,
	DBL_TroCapCLGD = IT_BANGLUONGTHANG0109.TCCHAMLOGIADINHMOI,
	DBL_TroCapHTDP = IT_BANGLUONGTHANG0109.TCHOTRODONGPHUCMOI,
	DBL_TroCapQAQIP = IT_BANGLUONGTHANG0109.TCQAQIPMOI,
	DBL_TrocapThoRap = IT_BANGLUONGTHANG0109.TCTHORAPMOI,
	DBL_TrocapHSE = IT_BANGLUONGTHANG0109.TCHSEMOI,
	DBL_HTNG = IT_BANGLUONGTHANG0109.TCHTNGMOI,
	DBL_DQTV = IT_BANGLUONGTHANG0109.TCDQTVMOI,
	DBL_PCCC = IT_BANGLUONGTHANG0109.TCPCCCMOI
	from IT_BANGLUONGTHANG0109 INNER JOIN ST_NHANVIEN ON IT_BANGLUONGTHANG0109.NV_MA = ST_NHANVIEN.NV_MA
								INNER JOIN ST_DONVI ON ST_NHANVIEN.DV_MA = ST_DONVI.DV_MA
								LEFT JOIN ST_CONGVIEC ON ST_NHANVIEN.CV_MA = ST_CONGVIEC.CV_MA
								LEFT JOIN ST_CHUCVU  ON ST_NHANVIEN.CVU_MA = ST_CHUCVU.CVU_MA
	WHERE T_MA = @T_MA AND LOAI_TL = 'TT'
						AND ST_NHANVIEN.NV_Ma not in ('000998')
						AND ST_NHANVIEN.DV_MA NOT LIKE N'%CG%'
						AND ST_NHANVIEN.DV_MA NOT LIKE N'%BGD%'
						AND	ST_NHANVIEN.DV_MA NOT LIKE('HCM%')
	ORDER BY IT_BANGLUONGTHANG0109.NV_Ma
END

