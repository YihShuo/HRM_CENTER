------------------Hệ Thống Mới Lấy Theo Hết DV (trích trong Hàm:fnThongKeGioCongTheoXuongDiemDanhTrongGio)----------
-- Lấy Đơn Vị Theo IT_DiemDanhHangNgay (Hoặc trong ST_GIOQUETTHE lấy theo DV_MA, không lấy theo DV_MATL) (Giờ Bình Thường Lấy Theo CC_GIOTHUCTE)
SELECT IT_DIEMDANHHANGNGAY.DV_MA,X_MA_,DV_TEN 
			--,SUM( ISNULL(CC_GIOTHUCTE,0) ) AS TONGBT
			,SUM(ISNULL(CC_GIOBINHTHUONG,0)+ISNULL(CC_GIOBINHTHUONGTAY,0) ) AS TONGBT --Adrew
			--,SUM( ISNULL(CC_GIOTANGCA,0) ) AS TONGTC 
			,SUM( ISNULL(CC_GIOTANGCA,0)+ISNULL(CC_GIOTANGCATAY,0)) AS TONGTC  --Andrew
FROM ST_GIOQUETTHE INNER JOIN IT_DIEMDANHHANGNGAY ON IT_DIEMDANHHANGNGAY.NV_MA = ST_GIOQUETTHE.NV_MA 
				   INNER JOIN ST_DONVI ON ST_DONVI.DV_MA = IT_DIEMDANHHANGNGAY.DV_MA
WHERE QT_NGAY >= '2021-11-02' AND QT_NGAY <= '2021-11-02'
		AND NGAY  = '2021-11-02'
		AND X_MA_ = N'TM'
		AND X_MA_ NOT IN ('KB','TAM','DT')
		AND ST_GIOQUETTHE.DV_MA='GO05'
GROUP BY X_MA_,IT_DIEMDANHHANGNGAY.DV_MA,DV_TEN 

--So Sánh Với Scrip IT làm Báo Cáo NS (Giờ Bình Thường Lấy Theo CC_GIOBINHTHUONG)
select DV_MA,TTCV,sum(GioBT)BT,sum(Tangca)TANGCA,sum(Tong)Tong from
(
select B.DV_MA,C.TTCV,ISNULL(CC_GIOBINHTHUONG,0)+ISNULL(CC_GIOBINHTHUONGTAY,0)GioBT
		,ISNULL(CC_GIOTANGCA,0)+ISNULL(CC_GIOTANGCATAY,0) TANGCA
		,ISNULL(CC_GIOBINHTHUONG,0)+ISNULL(CC_GIOTANGCA,0)+ISNULL(CC_GIOBINHTHUONGTAY,0)+ISNULL(CC_GIOTANGCATAY,0) Tong
from ST_GIOQUETTHE A left join ST_NHANVIEN B on A.NV_MA=B.NV_Ma 
				     LEFT join ST_CONGVIEC C on C.CV_MA=B.CV_MA
where QT_NGAY='2021-11-02' and (CC_GIOBINHTHUONG>=1 or CC_GIOBINHTHUONGTAY>=1) 
)A
Where a.DV_MA not like 'NV%'
	  AND a.DV_MA = 'GO05'
Group by DV_MA,TTCV
Order by DV_MA
