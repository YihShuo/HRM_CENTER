--cần lưu ý các đối tượng sinh ra trong dbo.VIEW_DS_KST_KTT7T_KTS có code như sau:
SELECT DISTINCT  PHUNUMANGTHAI.NV_MA, PHUNUMANGTHAI.NGAYMANGTHAI, PHUNUMANGTHAI.NGAYVE15H30, PHUNUMANGTHAI.NGAYDUSINH, dbo.IT_PNMT_SAYTHAI.NGAYSAYTHAI, dbo.IT_PNMT_SAYTHAI.NGAYKTSAYTHAI, 
                 THAITREN7THANG.BATDAUTU, THAITREN7THANG.DENNGAY, THAISANNUOICONNHO.TUNGAY AS TUNGAYTS, THAISANNUOICONNHO.DENNGAY AS DENNGAYTS
FROM
	 (SELECT dbo.IT_PNMT.NV_MA, dbo.IT_PNMT.NGAYMANGTHAI, dbo.IT_PNMT.NGAYVE15H30, dbo.IT_PNMT.NGAYDUSINH, dbo.IT_PNMT.SOLANMT
      FROM  dbo.IT_PNMT INNER JOIN (SELECT        NV_MA, MAX(NGAYMANGTHAI) AS NGAYMANGTHAI
                                    FROM          dbo.IT_PNMT AS IT_PNMT_1
                                    WHERE        (NV_MA NOT IN (SELECT        NV_Ma
                                                                FROM          dbo.ST_NHANVIENTHOIVIEC))
                                    GROUP BY NV_MA) 
									AS A ON dbo.IT_PNMT.NV_MA = A.NV_MA 
										 AND dbo.IT_PNMT.NGAYMANGTHAI = A.NGAYMANGTHAI) AS PHUNUMANGTHAI 
						LEFT OUTER JOIN dbo.IT_PNMT_SAYTHAI ON PHUNUMANGTHAI.NV_MA = dbo.IT_PNMT_SAYTHAI.NV_MA 
															AND PHUNUMANGTHAI.NGAYMANGTHAI = dbo.IT_PNMT_SAYTHAI.NGAYMANGTHAI
						LEFT OUTER JOIN (SELECT NV_MA, BATDAUTU, DENNGAY
										FROM    dbo.IT_THAITHANGTHU7
										WHERE   (NV_MA NOT IN
                                                        (SELECT        NV_Ma
                                                        FROM            dbo.ST_NHANVIENTHOIVIEC AS ST_NHANVIENTHOIVIEC_2))
							              ) AS THAITREN7THANG ON PHUNUMANGTHAI.NV_MA = THAITREN7THANG.NV_MA 
															AND   PHUNUMANGTHAI.NGAYVE15H30 = THAITREN7THANG.BATDAUTU 
						LEFT OUTER JOIN (SELECT        NV_MA, TUNGAY, DENNGAY, SOLAN
										FROM            dbo.IT_NUOICONDUOI12THANG
										WHERE        (NV_MA NOT IN
                                                             (SELECT        NV_Ma
                                                               FROM            dbo.ST_NHANVIENTHOIVIEC AS ST_NHANVIENTHOIVIEC_1))
						                 ) AS THAISANNUOICONNHO ON PHUNUMANGTHAI.NV_MA = THAISANNUOICONNHO.NV_MA 
																AND PHUNUMANGTHAI.SOLANMT = THAISANNUOICONNHO.SOLAN
WHERE        (dbo.IT_PNMT_SAYTHAI.NGAYSAYTHAI IS NULL) AND (dbo.IT_PNMT_SAYTHAI.NGAYKTSAYTHAI IS NULL) 
			 AND (THAITREN7THANG.BATDAUTU IS NULL) AND (THAITREN7THANG.DENNGAY IS NULL) 
			 AND (THAISANNUOICONNHO.TUNGAY IS NULL) AND (THAISANNUOICONNHO.DENNGAY IS NULL)