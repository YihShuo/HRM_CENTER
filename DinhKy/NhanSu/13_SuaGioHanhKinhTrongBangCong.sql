SELECT ST_NHANVIEN.NV_Ma,
		RIGHT('02-2020',4) AS NAM ,
		LEFT('02-2020',2) AS THANG ,
		TONGSOGIODUOCHUONG = 1.5 - SUM(CASE WHEN NOT IT_PHUNUHANHKINH.NV_MA IS NULL THEN 0.5 ELSE 0 END),
		NV_GioiTinh= isnull(ST_NHANVIEN.NV_GioiTinh ,0),
		NV_Ngayvao ,0
FROM ST_NHANVIEN LEFT JOIN IT_PHUNUHANHKINH ON ST_NHANVIEN.NV_Ma = IT_PHUNUHANHKINH.NV_MA
												AND MONTH(IT_PHUNUHANHKINH.NGAY)= MONTH('2022-02-28') 
												AND YEAR(IT_PHUNUHANHKINH.NGAY)= YEAR('2022-02-28')
				INNER JOIN ST_DONVI ON ST_NHANVIEN.DV_MA = ST_DONVI.DV_MA AND ISNULL(DV_LocBB ,0) = 0 AND ISNULL(DV_TV ,0) <> 1
WHERE NV_GioiTinh = 0
		AND ST_NHANVIEN.NV_Ma NOT IN (SELECT NV_Ma FROM ST_NHANVIENTHOIVIEC )
		AND ST_DONVI.DV_MA NOT LIKE '%CG%' AND ST_DONVI.DV_MA NOT IN ('BGD','BGDX')
		--- NGOAI LE
		AND YEAR(GETDATE()) - YEAR(NV_NGAYSINH) < 55 
		AND ST_NHANVIEN.CVU_MA NOT IN ('PCN','CNHIEM','TL','XT','PGD','GD','PHL','HL','T')
		AND NV_Ngayvao <= '2022-02-28'
		AND ST_NHANVIEN.NV_MA NOT IN (SELECT NV_MA FROM IT_SOGIONGHIHANHKINH WHERE THANG =  MONTH('2022-02-28') AND NAM = YEAR('2022-02-28') AND ISNULL(TINHNGHIVIEC,0) = 1)
		AND ST_NHANVIEN.NV_Ma='314671'
GROUP BY  ST_NHANVIEN.NV_Ma,ST_NHANVIEN.NV_Ten,ST_NHANVIEN.DV_MA,ST_NHANVIEN.NV_Ngayvao,NV_GioiTinh
