DECLARE @NGAYCUOITHANG NVARCHAR(10),@NGAYDAUTHANG NVARCHAR(10)
SET @NGAYDAUTHANG = RIGHT('01-2022',4)+'-' + LEFT('01-2022',2) + '-01'
SET @NGAYCUOITHANG =  CONVERT(NVARCHAR(10),(SELECT DATEADD(d,-1, DATEADD(mm, DATEDIFF(mm, 0 ,CONVERT(DATE,@NGAYDAUTHANG))+1, 0)) ),21)
SELECT STT= '',IT_NUOICONDUOI6TUOI.MANV
		,NV_Ten 
		,ST_NHANVIEN.DV_MA 
		,T_MA='01-2022'
		,NGAYNHAP 
		,IT_NUOICONDUOI6TUOI.NGAYSANHCON
		,NGAYHETHAN
		,TUOI=(DATEDIFF(MONTH,IT_NUOICONDUOI6TUOI.NGAYSANHCON,@NGAYCUOITHANG)/12)
		,THANGTUOI=(DATEDIFF(MONTH,IT_NUOICONDUOI6TUOI.NGAYSANHCON,@NGAYCUOITHANG)%12)
		,SOCON_SD=(ISNULL(IT_NUOICONDUOI6TUOI.SOCON_SD,0))
		,CHK_SANHDOI= ISNULL(IT_NUOICONDUOI6TUOI.CHK_SANHDOI,0)
		,SOTIENTC=(CASE WHEN (ISNULL(IT_NUOICONDUOI6TUOI.CHK_SANHDOI,0)=1) THEN (ISNULL(IT_NUOICONDUOI6TUOI.SOCON_SD,0) * 100.000) ELSE 100.000 END)
		,SOTIENDUOCHUONG = CONVERT(FLOAT,TROCAPCONDUOI6T.SOTIEN * 1000)
		,HD_NgayKy
		,DAKY=(CASE WHEN HD_NgayKy  IS NOT NULL THEN 'X' ELSE NULL END)

FROM IT_NUOICONDUOI6TUOI
						INNER JOIN ST_NHANVIEN ON ST_NHANVIEN.NV_MA=IT_NUOICONDUOI6TUOI.MANV
						LEFT JOIN ST_DONVI ON ST_NHANVIEN.DV_MA = ST_DONVI.DV_MA
						LEFT JOIN ST_HOPDONGLAODONG ON ST_NHANVIEN.NV_MA = ST_HOPDONGLAODONG.NV_MA
						LEFT JOIN ST_NHANVIENTHOIVIEC ON ST_NHANVIEN.NV_MA = ST_NHANVIENTHOIVIEC.NV_MA

						LEFT JOIN 
								(
								SELECT MANV,NGAYSANHCON,T_MA,CHK_SANHDOI=ISNULL(CHK_SANHDOI,0),SOCON_SD = ISNULL(SOCON,0),SOTIEN 
								FROM IT_QT_TROCAPCONDUOI6TUOI 
								WHERE T_MA = '01-2022'
								) AS TROCAPCONDUOI6T ON ( IT_NUOICONDUOI6TUOI.MANV = TROCAPCONDUOI6T.MANV
															AND  IT_NUOICONDUOI6TUOI.NGAYSANHCON = TROCAPCONDUOI6T.NGAYSANHCON )

WHERE ((DATEDIFF(MONTH,IT_NUOICONDUOI6TUOI.NGAYSANHCON,@NGAYCUOITHANG)/12) <6
			OR ((DATEDIFF(MONTH,IT_NUOICONDUOI6TUOI.NGAYSANHCON,@NGAYCUOITHANG)/12)=6 
			AND ((DATEDIFF(MONTH,IT_NUOICONDUOI6TUOI.NGAYSANHCON,@NGAYCUOITHANG)%12))BETWEEN 0 AND 0))
	AND IT_NUOICONDUOI6TUOI.MANV NOT IN (SELECT NV_MA FROM ST_NHANVIENTHOIVIEC)
	and ST_NHANVIEN.DV_MA NOT LIKE 'NV%' 
	AND ST_NHANVIEN.DV_MA NOT LIKE '%CG%' 
	AND ST_NHANVIEN.DV_MA NOT LIKE 'DT%' 
	AND ST_NHANVIEN.DV_MA not in ('BGD','BGDX') 
		--AND NV_GIOITINH= 0
ORDER BY (DATEDIFF(MONTH,IT_NUOICONDUOI6TUOI.NGAYSANHCON,@NGAYCUOITHANG)/12),(DATEDIFF(MONTH,IT_NUOICONDUOI6TUOI.NGAYSANHCON,@NGAYCUOITHANG)%12)

