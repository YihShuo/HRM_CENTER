 SELECT b.CC_GIOTANGCA,b.QT_NGAYCAPNHAT,* 
 FROM MF_Record a INNER JOIN ST_GIOQUETTHE b ON a.UserNo = b.NV_MA
 WHERE  MatTime >='2024-06-28 12:00' 
 AND CONVERT(DATE, MatTime)='2024-06-28'
 AND b.CC_GIOTANGCA > '4'
 ORDER BY a.DevNo


 

 SELECT b.CC_GIOTANGCA,b.QT_NGAYCAPNHAT,* 
 FROM MF_Record a INNER JOIN ST_GIOQUETTHE b ON a.UserNo = b.NV_MA
 WHERE YEAR(a.MatTime) = '2024'
AND MONTH(a.MatTime) = '6'
 AND b.CC_GIOTANGCA > '4'
