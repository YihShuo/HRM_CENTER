SELECT  NV_TEN,ST_NHANVIEN.DV_MA,TABLETONGNNDH.NV_MA,NV_NGAYVAO,
			PN_Songaynamtruoc,PN_Songaynamnay,PN_NangnhocDH,PN_PhepTren5Nam,PN_SothanglamNNDH,TONGCONGPHEP,
			LAMTRON= CASE WHEN  ( CHARINDEX('.',TONGCONGPHEP,1) >0 AND ( REVERSE(left(REVERSE(TONGCONGPHEP),CHARINDEX('.',REVERSE(TONGCONGPHEP),1)-1))>=50 )) --Nếu có thập phân và phần thập phân đó lớn hơn hoặc bằng 50
							THEN CONVERT(INT,  ( LEFT(TONGCONGPHEP,CHARINDEX ('.',TONGCONGPHEP,1)-1)  ))   +1       -- Thì lấy phần nguyên cộng thêm 1
						  WHEN CHARINDEX('.',TONGCONGPHEP,1) >0 AND  LEN( REVERSE(left(REVERSE(TONGCONGPHEP),CHARINDEX('.',REVERSE(TONGCONGPHEP),1)-1)))=1 AND REVERSE(left(REVERSE(TONGCONGPHEP),CHARINDEX('.',REVERSE(TONGCONGPHEP),1)-1))>=5
							THEN CONVERT(INT,  ( LEFT(TONGCONGPHEP,CHARINDEX ('.',TONGCONGPHEP,1)-1)  ))   +1												 --Nếu có thập phân và phần thập phân đó chỉ có 1 số >=5 thì lấy phần nguyên cộng thêm 1
						  WHEN CHARINDEX('.',TONGCONGPHEP,1)>0  AND   ( REVERSE(left(REVERSE(TONGCONGPHEP),CHARINDEX('.',REVERSE(TONGCONGPHEP),1)-1))<50 )
							THEN CONVERT(INT,  ( LEFT(TONGCONGPHEP,CHARINDEX ('.',TONGCONGPHEP,1)-1)  ))			--Thì lấy phần nguyên
						  ELSE  TONGCONGPHEP  END,
			(CASE WHEN isnull(PN_Songaynamtruoc,0) >0 
					THEN ISNULL(PN_Songaynamnay,0)+ ISNULL(PN_NangnhocDH,0) + ISNULL(PN_PhepTren5Nam ,0) + isnull(PN_Songaynamtruoc,0)
				  ELSE
					ISNULL(PN_Songaynamnay,0)+ ISNULL(PN_NangnhocDH,0) + ISNULL(PN_PhepTren5Nam ,0) - ABS (isnull(PN_Songaynamtruoc,0))
			END) AS TONGCONG
			,T1.TONGSONGAY AS T1
			,T2.TONGSONGAY AS T2
			,T3.TONGSONGAY AS T3
			,T4.TONGSONGAY AS T4
			,T5.TONGSONGAY AS T5
			,T6.TONGSONGAY AS T6
			,T7.TONGSONGAY AS T7
			,T8.TONGSONGAY AS T8
			,T9.TONGSONGAY AS T9
			,T10.TONGSONGAY AS T10
			,T11.TONGSONGAY AS T11
			,T12.TONGSONGAY AS T12
			,TONGSONGAY_CTYDUYET =
								(ISNULL(T1.TONGSONGAY_CTDUYET,0) +
								ISNULL(T2.TONGSONGAY_CTDUYET,0) +
								ISNULL(T3.TONGSONGAY_CTDUYET,0) +
								ISNULL(T4.TONGSONGAY_CTDUYET,0) +
								ISNULL(T5.TONGSONGAY_CTDUYET,0) +
								ISNULL(T6.TONGSONGAY_CTDUYET,0) +
								ISNULL(T7.TONGSONGAY_CTDUYET,0) +
								ISNULL(T8.TONGSONGAY_CTDUYET,0) +
								ISNULL(T9.TONGSONGAY_CTDUYET,0) +
								ISNULL(T10.TONGSONGAY_CTDUYET,0) +
								ISNULL(T11.TONGSONGAY_CTDUYET,0) +
								ISNULL(T12.TONGSONGAY_CTDUYET,0) )
	FROM ST_NHANVIEN INNER JOIN ST_DONVI ON ST_NHANVIEN.DV_MA = ST_DONVI.DV_MA
					LEFT JOIN                dbo.TINHSONGAYPHEPTRONGTHANG_('12','2025') AS T12 ON ST_NHANVIEN.NV_MA = T12.NV_MA 
					LEFT JOIN (SELECT * FROM dbo.TINHSONGAYPHEPTRONGTHANG_('11','2025')) AS T11 ON ST_NHANVIEN.NV_MA = T11.NV_MA 
					LEFT JOIN (SELECT * FROM dbo.TINHSONGAYPHEPTRONGTHANG_('10','2025')) AS T10 ON ST_NHANVIEN.NV_MA = T10.NV_MA 
					LEFT JOIN (SELECT * FROM dbo.TINHSONGAYPHEPTRONGTHANG_('09','2025')) AS T9 ON ST_NHANVIEN.NV_MA = T9.NV_MA 
					LEFT JOIN (SELECT * FROM dbo.TINHSONGAYPHEPTRONGTHANG_('08','2025')) AS T8 ON ST_NHANVIEN.NV_MA = T8.NV_MA 
					LEFT JOIN (SELECT * FROM dbo.TINHSONGAYPHEPTRONGTHANG_('07','2025')) AS T7 ON ST_NHANVIEN.NV_MA = T7.NV_MA 
					LEFT JOIN (SELECT * FROM dbo.TINHSONGAYPHEPTRONGTHANG_('06','2025')) AS T6 ON ST_NHANVIEN.NV_MA = T6.NV_MA
					LEFT JOIN (SELECT * FROM dbo.TINHSONGAYPHEPTRONGTHANG_('05','2025')) AS T5 ON ST_NHANVIEN.NV_MA = T5.NV_MA  
					LEFT JOIN (SELECT * FROM dbo.TINHSONGAYPHEPTRONGTHANG_('04','2025')) AS T4 ON ST_NHANVIEN.NV_MA = T4.NV_MA 
					LEFT JOIN (SELECT * FROM dbo.TINHSONGAYPHEPTRONGTHANG_('03','2025')) AS T3 ON ST_NHANVIEN.NV_MA = T3.NV_MA 
					LEFT JOIN (SELECT * FROM dbo.TINHSONGAYPHEPTRONGTHANG_('02','2025')) AS T2 ON ST_NHANVIEN.NV_MA = T2.NV_MA 
					LEFT JOIN (SELECT * FROM dbo.TINHSONGAYPHEPTRONGTHANG_('01','2025')) AS T1 ON ST_NHANVIEN.NV_MA = T1.NV_MA
					INNER JOIN (Select  ST_PHEPNAM.NV_Ma , TONGCONGPHEP =  ROUND( isnull(PN_Songaynamnay,0)
																		   + isnull(PN_PhepTren5Nam,0)
																		   + (convert(real, 2 )/ convert (real,12))*ISNULL(PN_SothanglamNNDH,0) ,2)--Tỷ Bách: đang 6T > 1 ngày;12T >2 ngày.
										,PN_Songaynamtruoc,PN_Songaynamnay,PN_NangnhocDH,PN_PhepTren5Nam,PN_SothanglamNNDH
								from  dbo.ST_PHEPNAM
								where  PN_NAM = '2025' and NOT EXISTS (SELECT NV_MA FROM ST_NHANVIENTHOIVIEC TV WHERE TV.NV_MA = ST_PHEPNAM.NV_MA )
								) AS TABLETONGNNDH on ST_NHANVIEN.NV_Ma =TABLETONGNNDH.NV_Ma 
	WHERE  ST_NHANVIEN.NV_Ma = '315064'
	ORDER by nv_ma


