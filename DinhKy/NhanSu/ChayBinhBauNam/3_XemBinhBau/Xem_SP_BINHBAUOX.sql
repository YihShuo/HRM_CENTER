
	DECLARE 
			@NAM_ char(4),
			@TUNGAY char(7),
			@DENNGAY char(7),
			
			@NAM char(4),
			@NAMSAU CHAR(4),
			@NAMTHANGNGAYVAO CHAR(10),
			@NAMTHANGNGAYTV CHAR(10),
			@SOTHANG INT

			SET @NAM_='2020'
			SET @TUNGAY='01-2020'
			SET @DENNGAY = '12-2020'

			SET @NAM = @NAM_
			SET @NAMSAU = @NAM + 1 
			SET @NAMTHANGNGAYVAO = @NAM + '-'+ '01'+ '-'+'15'
			--SET @NAMTHANGNGAYTV = @NAM + '-'+'09'+'-'+'30'
			SET @NAMTHANGNGAYTV = @NAM + '-'+'12'+'-'+'31'
			SET @SOTHANG = CONVERT(INT,LEFT (@DENNGAY,2))


	SELECT  STT=0, 
			NAM = @NAM_,
			dbo.ST_NHANVIEN.NV_Ten ,
			dbo.ST_NHANVIEN.NV_Ngayvao, 
			GT_NAM =CASE WHEN NV_GIOITINH=1 THEN 'X' ELSE '' END, 
			NU=CASE WHEN NV_GIOITINH=0 THEN 'X' ELSE '' END,  
			dbo.ST_BINHBAUTHANG.NV_MA, 
			dbo.ST_NHANVIEN.DV_MA AS DV_MA, 
			ST_NHANVIEN.NV_Ngaysinh, 
			'OX' AS BBN ,
			SUM(CASE WHEN BB_MA = 'A' THEN 1 ELSE 0 END) AS BBA, SUM(CASE WHEN BB_MA = 'B' THEN 1 ELSE 0 END) AS BBB, 
			SUM(CASE WHEN BB_MA = 'C' THEN 1 ELSE 0 END) AS BBC, SUM(CASE WHEN BB_MA = 'D' THEN 1 ELSE 0 END) AS BBD, 
			SUM(CASE WHEN BB_MA = 'OX' THEN 1 ELSE 0 END) AS BBOX, SUM(CASE WHEN BB_MA = 'HS' THEN 1 ELSE 0 END) AS BBHS, 
			SUM(CASE WHEN BB_SONGAYOO IS NULL THEN 0 ELSE CONVERT(FLOAT, BB_SONGAYOO) END) / 8 AS SONGAYOO, 
			SUM(CASE WHEN BB_SONGAYRO IS NULL THEN 0 ELSE CONVERT(FLOAT, BB_SONGAYRO) END) / 8 AS SONGAYRO, 
			SUM(CASE WHEN BB_SONGAYCO IS NULL THEN 0 ELSE CONVERT(FLOAT, BB_SONGAYCO) END) / 8 AS SONGAYCO, 
			SUM(CASE WHEN BB_SONGAYO IS NULL  AND T_MA>= @TUNGAY AND T_MA<= @DENNGAY 
			THEN 0 ELSE CONVERT(FLOAT, BB_SONGAYO) END) / 8 AS SONGAYO, 
			SUM(CASE WHEN BB_SONGAYOTC IS NULL THEN 0 ELSE CONVERT(FLOAT, BB_SONGAYOTC) END) / 8 AS SONGAYOTC,
			CASE WHEN  PN_Songaynamtruoc = -1 THEN SUM(CASE WHEN BB_SoNgayP IS NULL THEN 0 ELSE CONVERT(FLOAT, BB_SONGAYP) END) / 8 + 1 
				 ELSE SUM(CASE WHEN BB_SoNgayP IS NULL THEN 0 ELSE CONVERT(FLOAT, BB_SONGAYP) END) / 8 END AS SONGAYP,
			SUM(CASE WHEN BB_SONGAYKTHAI IS NULL THEN 0 ELSE CONVERT(FLOAT, BB_SONGAYKTHAI) END) / 8 AS SONGAYKTHAI, 
			SUM(CASE WHEN BB_SONGAYR IS NULL THEN 0 ELSE CONVERT(FLOAT, BB_SONGAYR) END) / 8 AS SONGAYR,
			SUM(CASE WHEN BB_SONGAYR1 IS NULL THEN 0 ELSE CONVERT(FLOAT, BB_SONGAYR1) END) / 8 AS SONGAYR1, -- Andrew 
			SUM(CASE WHEN BB_SONGAYS IS NULL THEN 0 ELSE CONVERT(FLOAT, BB_SONGAYS) END) / 8 AS SONGAYS, 
			SUM(CASE WHEN BB_SONGAYNO IS NULL THEN 0 ELSE CONVERT(FLOAT, BB_SONGAYNO) END) / 8 AS SONGAYNO, 
			SUM(CASE WHEN BB_SONGAYKHHGD IS NULL THEN 0 ELSE CONVERT(FLOAT, BB_SONGAYKHHGD) END) / 8 AS SONGAYKHHGD, 
			SUM(CASE WHEN BB_SONGAYQS IS NULL THEN 0 ELSE CONVERT(FLOAT, BB_SONGAYQS) END) / 8 AS SONGAYQS, 
			SUM(CASE WHEN BB_SONGAYTSAN IS NULL THEN 0 ELSE CONVERT(FLOAT, BB_SONGAYTSAN) END) / 8 AS SONGAYTSAN, 
			SUM(CASE WHEN BB_SONGAYTNLD IS NULL THEN 0 ELSE CONVERT(FLOAT, BB_SONGAYTNLD) END) / 8 AS SONGAYTNLD,
			SUM(CASE WHEN BB_SONGAYDQ IS NULL THEN 0 ELSE CONVERT(FLOAT, BB_SONGAYDQ) END) / 8 AS SONGAYDQ,
			SUM(CASE WHEN BB_SONGAYDS IS NULL THEN 0 ELSE CONVERT(FLOAT, BB_SONGAYDS) END) / 8 AS SONGAYDS,
			SUM(CASE WHEN BB_SONGAYST IS NULL THEN 0 ELSE CONVERT(FLOAT, BB_SONGAYST) END) / 8 AS SONGAYST 

			FROM dbo.ST_BINHBAUTHANG INNER JOIN dbo.ST_NHANVIEN ON dbo.ST_BINHBAUTHANG.NV_MA = dbo.ST_NHANVIEN.NV_Ma
			AND T_MA>= @TUNGAY  AND T_MA<= @DENNGAY AND RIGHT(ST_BINHBAUTHANG.T_MA, 4) =@NAM_ 
			LEFT JOIN ST_PHEPNAM   ON ST_NHANVIEN.NV_Ma = ST_PHEPNAM.NV_MA AND ST_PHEPNAM.PN_Nam  = @NAM_
			INNER JOIN ST_DONVI ON ST_NHANVIEN.DV_MA = ST_DONVI .DV_MA AND DV_LocBB = 0
			--Andrew
	WHERE (dbo.ST_NHANVIEN.NV_Ma NOT IN
										(SELECT  NV_Ma
										FROM dbo.ST_NHANVIENTHOIVIEC
										WHERE (TV_NgayThoiViec <= @NAMTHANGNGAYTV))
		   ) 
		  AND (dbo.ST_NHANVIEN.DV_MA NOT IN ('NV', 'NV1', 'NV01', 'NV02', 'NV03', 'NV 04', 'NV05', 'NV06', 'NV07', 'NV08', 'NV09', 'NV10', 'NV11', 'NV12', 'NV13', 'NV14', 'NV15', 'NV16', 'NV17', 'NV18', 'NV19', 'KB','T', 'T01','T02','T03'))
		  AND ST_BINHBAUTHANG.T_MA <=@DENNGAY 
		--AND ST_NHANVIEN.DV_MA NOT LIKE 'DT%' 
		  AND ST_NHANVIEN.DV_MA NOT IN ('A1MDT','A2MDT') 
		--AND ST_NHANVIEN.NV_MA = '325656'
		  AND (--Điều Kiện lấy bình bầu tường hợp làm không đủ tháng (CN mới) hoặc làm trọn đủ tháng (CN cũ)
						(--Điều kiện này sẽ dựa vào ngày KHD được chuyển về cùng định dạng T_MA để xét từng tháng bình bầu nào thỏa điều kiện xét cuối năm
							(	
									----NV Ký HD sau ngày 15 thì các T_MA được xét tính sẽ dựa vào ngày HDD KHÔNG ĐƯỢC LÀM TRÒN tháng, được chuyển về cùng định dạng T_MA (MM_yyyy)
								t_ma >= (substring(convert(char(10),DATEADD(M,1,NV_NGAYKHD_),105),4,7))  AND DAY(NV_NGAYKHD_) > 15 		
								OR ----NV Ký HD trước ngày 15 thì các T_MA được xét tính sẽ dựa vào ngày HDD ĐƯỢC LÀM TRÒN tháng, được chuyển về cùng định dạng T_MA (MM_yyyy)
								t_ma >=	(substring(CONVERT(char(10), CAST(NV_NGAYKHD_ AS DATETIME), 105),4,7))  AND DAY(NV_NGAYKHD_) <= 15
							)   
						AND NV_SOTHANG < @SOTHANG
					) 
					OR NV_SOTHANG = @SOTHANG
			   )

	GROUP BY dbo.ST_NHANVIEN.DV_MA, dbo.ST_NHANVIEN.NV_Ten, PN_Songaynamtruoc ,dbo.ST_BINHBAUTHANG.NV_MA, dbo.ST_NHANVIEN.NV_Ngayvao, ST_NHANVIEN.NV_Ngaysinh,ST_NHANVIEN.NV_SOTHANG,
			CASE WHEN NV_GIOITINH=1 THEN 'X' ELSE '' END, 
			CASE WHEN NV_GIOITINH=0 THEN 'X' ELSE '' END 
	--Andrew
	HAVING SUM(CASE WHEN BB_MA = 'OX' THEN 1 ELSE 0 END) 
			>= ST_NHANVIEN.NV_SOTHANG --Có tấc cả tháng được tính BB đều OX 
UNION 
	SELECT  STT=0,
			NAM=@NAM_,
			dbo.ST_NHANVIEN.NV_Ten ,
			dbo.ST_NHANVIEN.NV_Ngayvao, 
			NAM=CASE WHEN NV_GIOITINH=1 THEN 'X' ELSE '' END, 
			NU=CASE WHEN NV_GIOITINH=0 THEN 'X' ELSE '' END,  
			dbo.ST_BINHBAUTHANG.NV_MA, 
			dbo.ST_NHANVIEN.DV_MA, 
			ST_NHANVIEN.NV_Ngaysinh, 
			'OX' AS BBN ,
			SUM(CASE WHEN BB_MA = 'A' THEN 1 ELSE 0 END) AS BBA, SUM(CASE WHEN BB_MA = 'B' THEN 1 ELSE 0 END) AS BBB, 
			SUM(CASE WHEN BB_MA = 'C' THEN 1 ELSE 0 END) AS BBC, SUM(CASE WHEN BB_MA = 'D' THEN 1 ELSE 0 END) AS BBD, 
			SUM(CASE WHEN BB_MA = 'OX' THEN 1 ELSE 0 END) AS BBOX, SUM(CASE WHEN BB_MA = 'HS' THEN 1 ELSE 0 END) AS BBHS, 
			SUM(CASE WHEN BB_SONGAYOO IS NULL THEN 0 ELSE CONVERT(FLOAT, BB_SONGAYOO) END) / 8 AS SONGAYOO, 
			SUM(CASE WHEN BB_SONGAYRO IS NULL THEN 0 ELSE CONVERT(FLOAT, BB_SONGAYRO) END) / 8 AS SONGAYRO, 
			SUM(CASE WHEN BB_SONGAYCO IS NULL THEN 0 ELSE CONVERT(FLOAT, BB_SONGAYCO) END) / 8 AS SONGAYCO, 
			SUM(CASE WHEN BB_SONGAYO IS NULL  AND T_MA>= @TUNGAY  
											  AND T_MA<= @DENNGAY 
						THEN 0 ELSE CONVERT(FLOAT, BB_SONGAYO) END) / 8 AS SONGAYO, 
			SUM(CASE WHEN BB_SONGAYOTC IS NULL THEN 0 ELSE CONVERT(FLOAT, BB_SONGAYOTC) END) / 8 AS SONGAYOTC,
			CASE WHEN  PN_Songaynamtruoc = -1 THEN SUM(CASE WHEN BB_SoNgayP IS NULL THEN 0 ELSE CONVERT(FLOAT, BB_SONGAYP) END) / 8 + 1 
				 ELSE SUM(CASE WHEN BB_SoNgayP IS NULL THEN 0 ELSE CONVERT(FLOAT, BB_SONGAYP) END) / 8 END AS SONGAYP, 
			SUM(CASE WHEN BB_SONGAYKTHAI IS NULL THEN 0 ELSE CONVERT(FLOAT, BB_SONGAYKTHAI) END) / 8 AS SONGAYKTHAI, 
			SUM(CASE WHEN BB_SONGAYR IS NULL THEN 0 ELSE CONVERT(FLOAT, BB_SONGAYR) END) / 8 AS SONGAYR, 
			SUM(CASE WHEN BB_SONGAYR1 IS NULL THEN 0 ELSE CONVERT(FLOAT, BB_SONGAYR1) END) / 8 AS SONGAYR1, -- Andrew
			SUM(CASE WHEN BB_SONGAYS IS NULL THEN 0 ELSE CONVERT(FLOAT, BB_SONGAYS) END) / 8 AS SONGAYS, 
			SUM(CASE WHEN BB_SONGAYNO IS NULL THEN 0 ELSE CONVERT(FLOAT, BB_SONGAYNO) END) / 8 AS SONGAYNO, 
			SUM(CASE WHEN BB_SONGAYKHHGD IS NULL THEN 0 ELSE CONVERT(FLOAT, BB_SONGAYKHHGD) END) / 8 AS SONGAYKHHGD, 
			SUM(CASE WHEN BB_SONGAYQS IS NULL THEN 0 ELSE CONVERT(FLOAT, BB_SONGAYQS) END) / 8 AS SONGAYQS, 
			SUM(CASE WHEN BB_SONGAYTSAN IS NULL THEN 0 ELSE CONVERT(FLOAT, BB_SONGAYTSAN) END) / 8 AS SONGAYTSAN, 
			SUM(CASE WHEN BB_SONGAYTNLD IS NULL THEN 0 ELSE CONVERT(FLOAT, BB_SONGAYTNLD) END) / 8 AS SONGAYTNLD,
			SUM(CASE WHEN BB_SONGAYDQ IS NULL THEN 0 ELSE CONVERT(FLOAT, BB_SONGAYDQ) END) / 8 AS SONGAYDQ,
			SUM(CASE WHEN BB_SONGAYDS IS NULL THEN 0 ELSE CONVERT(FLOAT, BB_SONGAYDS) END) / 8 AS SONGAYDS,
			SUM(CASE WHEN BB_SONGAYST IS NULL THEN 0 ELSE CONVERT(FLOAT, BB_SONGAYST) END) / 8 AS SONGAYST
	FROM dbo.ST_BINHBAUTHANG INNER JOIN dbo.ST_NHANVIEN ON dbo.ST_BINHBAUTHANG.NV_MA = dbo.ST_NHANVIEN.NV_Ma
														AND T_MA>= @TUNGAY  AND T_MA<= @DENNGAY 
							 LEFT JOIN ST_PHEPNAM   ON ST_NHANVIEN.NV_Ma = ST_PHEPNAM.NV_MA AND ST_PHEPNAM.PN_Nam  = @NAM_
	WHERE (dbo.ST_NHANVIEN.NV_Ma NOT IN
										(SELECT  NV_Ma
										FROM dbo.ST_NHANVIENTHOIVIEC
										WHERE (TV_NgayThoiViec <= @NAMTHANGNGAYTV))) AND (dbo.ST_NHANVIEN.DV_MA NOT IN ('NV', 'NV1', 'NV01', 'NV02', 'NV03', 'NV 04', 'NV05', 'NV06', 'NV07', 'NV08', 'NV09', 'NV10', 'NV11', 'NV12', 'NV13', 'NV14', 'NV15', 'NV16', 'NV17', 'NV18', 'NV19', 'KB','T', 'T01','T02','T03'))
										AND RIGHT(ST_BINHBAUTHANG.T_MA, 4) =@NAM_  AND ST_BINHBAUTHANG.T_MA <= @DENNGAY 
										AND ST_NHANVIEN.DV_MA NOT LIKE 'DT%' 
										AND ST_NHANVIEN.DV_MA NOT IN ('A1MDT','A2MDT') 
										AND (ST_NHANVIEN.NV_Ma IN    (SELECT NV_MA FROM KDTGNL2011))
			AND (--Điều Kiện lấy bình bầu tường hợp làm không đủ tháng (CN mới) hoặc làm trọn đủ tháng (CN cũ)
					(--Điều kiện này sẽ dựa vào ngày KHD được chuyển về cùng định dạng T_MA để xét từng tháng bình bầu nào thỏa điều kiện xét cuối năm
						(	
								----NV Ký HD sau ngày 15 thì các T_MA được xét tính sẽ dựa vào ngày HDD KHÔNG ĐƯỢC LÀM TRÒN tháng, được chuyển về cùng định dạng T_MA (MM_yyyy)
							t_ma >= (substring(convert(char(10),DATEADD(M,1,NV_NGAYKHD_),105),4,7))  AND DAY(NV_NGAYKHD_) > 15 		
							OR ----NV Ký HD trước ngày 15 thì các T_MA được xét tính sẽ dựa vào ngày HDD ĐƯỢC LÀM TRÒN tháng, được chuyển về cùng định dạng T_MA (MM_yyyy)
							t_ma >= (substring(CONVERT(char(10), CAST(NV_NGAYKHD_ AS DATETIME), 105),4,7))  AND DAY(NV_NGAYKHD_) <= 15
						)   
						AND NV_SOTHANG < @SOTHANG
					) OR NV_SOTHANG = @SOTHANG
				)
			AND ST_NHANVIEN.NV_TEN <>'' 
			
	GROUP BY dbo.ST_NHANVIEN.DV_MA, dbo.ST_NHANVIEN.NV_Ten,PN_Songaynamtruoc, dbo.ST_BINHBAUTHANG.NV_MA, dbo.ST_NHANVIEN.NV_Ngayvao, ST_NHANVIEN.NV_Ngaysinh,
				CASE WHEN NV_GIOITINH=1 THEN 'X' ELSE '' END, 
				CASE WHEN NV_GIOITINH=0 THEN 'X' ELSE '' END
