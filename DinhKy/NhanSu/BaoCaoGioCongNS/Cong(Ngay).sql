USE [P0104-TYTHAC]
GO
Declare @ngay as DateTime
Set @ngay='2022-03-09'

select DV_MA_,TTCV,sum(GioBT)BT,sum(Tangca)TANGCA,sum(Tong)Tong from
(
	select B.DV_MA_,C.TTCV,ISNULL(CC_GIOBINHTHUONG,0)+ISNULL(CC_GIOBINHTHUONGTAY,0)GioBT
			,ISNULL(CC_GIOTANGCA,0)+ISNULL(CC_GIOTANGCATAY,0) TANGCA
			,ISNULL(CC_GIOBINHTHUONG,0)+ISNULL(CC_GIOTANGCA,0)+ISNULL(CC_GIOBINHTHUONGTAY,0)+ISNULL(CC_GIOTANGCATAY,0) Tong
	from ST_GIOQUETTHE A left join ST_NHANVIEN B on A.NV_MA=B.NV_Ma 
	left join ST_CONGVIEC C on C.CV_MA=B.CV_MA
	where QT_NGAY=@ngay and (CC_GIOBINHTHUONG>=1 or CC_GIOBINHTHUONGTAY>=1 OR CC_GIOTHUCTE >=1) 
)A
Where a.DV_MA_ not like 'NV%'
Group by DV_MA_,TTCV
Order by DV_MA_

select DV_MA,TTCV,sum(Tangca)TANGCA from
(
	select B.DV_MA,C.TTCV,ISNULL(CC_GIOBINHTHUONG,0)+ISNULL(CC_GIOBINHTHUONGTAY,0)GioBT
			,ISNULL(CC_GIOTANGCA,0)+ISNULL(CC_GIOTANGCATAY,0) TANGCA
			,ISNULL(CC_GIOBINHTHUONG,0)+ISNULL(CC_GIOTANGCA,0)+ISNULL(CC_GIOBINHTHUONGTAY,0)+ISNULL(CC_GIOTANGCATAY,0) Tong
	from ST_GIOQUETTHE_ A left join ST_NHANVIEN B on A.NV_MA=B.NV_Ma 
	left join ST_CONGVIEC C on C.CV_MA=B.CV_MA
	where QT_NGAY=@ngay--and (CC_GIOBINHTHUONG>=2 or CC_GIOBINHTHUONGTAY>=2)
)A
Where a.DV_MA not like 'NV%'
Group by DV_MA,TTCV
Order by DV_MA