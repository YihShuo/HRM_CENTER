Declare @TuNgay as DateTime, @DenNgay as DateTime
Set @TuNgay='2022-02-28'
Set @DenNgay='2022-03-05'

----------lấy theo HRM
SELECT IT_DIEMDANHHANGNGAY.DV_MA,DV_TEN,TTCV			
					,SUM(ISNULL(CC_GIOBINHTHUONG,0)+ISNULL(CC_GIOBINHTHUONGTAY,0) ) AS TONGBT --Adrew			
					,SUM( ISNULL(CC_GIOTANGCA,0)+ISNULL(CC_GIOTANGCATAY,0)) AS TONGTC  --Andrew
					,[Tổng]= SUM(ISNULL(CC_GIOBINHTHUONG,0)+ISNULL(CC_GIOBINHTHUONGTAY,0) ) + SUM( ISNULL(CC_GIOTANGCA,0)+ISNULL(CC_GIOTANGCATAY,0))
FROM ST_GIOQUETTHE INNER JOIN IT_DIEMDANHHANGNGAY ON IT_DIEMDANHHANGNGAY.NV_MA = ST_GIOQUETTHE.NV_MA 
				   INNER JOIN ST_DONVI ON ST_DONVI.DV_MA = IT_DIEMDANHHANGNGAY.DV_MA
				   LEFT JOIN ST_NHANVIEN ON ST_GIOQUETTHE.NV_MA=ST_NHANVIEN.NV_Ma
				   LEFT JOIN ST_CONGVIEC ON ST_NHANVIEN.CV_MA=ST_CONGVIEC.CV_MA
WHERE QT_NGAY >= @TuNgay AND QT_NGAY <= @DenNgay
						 AND NGAY  = @DenNgay
						 AND X_MA_ = N'TM'
						 AND X_MA_ NOT IN ('KB','TAM','DT')
						 AND ST_DONVI.DV_MA NOT IN ('CG')
						--AND IT_DIEMDANHHANGNGAY.DV_MA = 'CHUANBI'
GROUP BY X_MA_,IT_DIEMDANHHANGNGAY.DV_MA,DV_TEN,TTCV
ORDER BY IT_DIEMDANHHANGNGAY.DV_MA


