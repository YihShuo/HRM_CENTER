----------------------Thống Kê Toàn ĐV
SELECT a.NV_MA,b.NV_Ten,a.DV_Ma,a.BB_MA
FROM ST_BINHBAUTHANG a INNER JOIN ST_NHANVIEN b ON a.NV_MA = b.NV_Ma
WHERE T_MA = '10-2023'
ORDER BY DV_Ma